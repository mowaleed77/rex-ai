class DocumentAgent(Agent):
    name = "document"

    SUPPORTED = {"curriculum_report", "course_description", "gap_analysis"}

    # ------------------------------------------------------------------ run
    def run(self, task: dict) -> AgentResult:
        doc_type = task.get("document_type")
        title = task.get("title") or ""
        content = task.get("content")
        meta = task.get("metadata") or {}
        output_dir = Path(task.get("output_dir", "generated_docs"))
        curriculum = task.get("curriculum")

        if doc_type not in self.SUPPORTED:
            return AgentResult(
                self.name, False,
                message="Unsupported document_type. Choose: " + ", ".join(sorted(self.SUPPORTED)),
            )
        if not isinstance(meta, dict):
            meta = {}
        meta = dict(meta)

        used_rag = False
        simple_lines = None
        stamp = None

        if curriculum is not None:
            if not isinstance(curriculum, dict) or not curriculum.get("modules"):
                return AgentResult(self.name, False, message="`curriculum` must be the Curriculum agent's output.")
            title = title or self._default_title(doc_type, curriculum)
            content = self._content_from_curriculum(doc_type, curriculum, task)
            if content is None:
                return AgentResult(self.name, False,
                                   message="Run the gap analysis first and pass its output as `gap`.")
            stamp = curriculum
            meta.setdefault("Course", curriculum.get("course", ""))
            meta.setdefault("Level", curriculum.get("level", ""))
            if curriculum.get("language") == "ar":
                from rex.utils.catalog import LEVEL_AR
                meta["Level"] = LEVEL_AR.get(meta["Level"], meta["Level"])
        elif isinstance(content, list) and content:
            if not all(isinstance(item, str) for item in content):
                return AgentResult(self.name, False, message="Every content item must be a string.")
            simple_lines = content
        elif isinstance(content, dict) and content:
            pass
        elif content in (None, [], {}):
            course_name = str(meta.get("Course", title))
            rag_context = self._rag_context(course_name)
            used_rag = bool(rag_context)
            content = self._auto_generate_content(doc_type, title, meta, rag_context)
        else:
            return AgentResult(self.name, False,
                               message="content must be a JSON object, a list of strings, or omitted.")

        title = title or "REX Academy Report"
        language = self._pick_language(task.get("language", "auto"), title, meta, content, simple_lines)
        if language == "ar":
            try:
                arabic.register_fonts()
            except FileNotFoundError as error:
                return AgentResult(self.name, False, message=str(error))
        self._lang = language
        self._rtl = language == "ar"
        labels = LABELS[language]

        if stamp is not None:
            meta["Version"] = str(stamp.get("version", 1))
            status = STATUS_TEXT[language].get(stamp.get("status_code", "draft"), "")
            if stamp.get("status_code") == "approved" and stamp.get("approved_by"):
                status += f" - {stamp['approved_by']}"
            meta["Status"] = status

        try:
            output_dir.mkdir(parents=True, exist_ok=True)
            safe_title = "".join(c for c in title if c.isalnum() or c in (" ", "_", "-")).strip().replace(" ", "_")
            output_path = output_dir / f"{doc_type}_{safe_title or 'document'}.pdf"

            styles = self._styles()
            story = []
            story += self._header(title, meta, styles)
            if simple_lines is not None:
                story += self._build_simple(simple_lines, styles)
            else:
                story += getattr(self, f"_build_{doc_type}")(content, styles)
            story += self._footer(styles, used_rag)

            footer_text = labels["footer_rag"] if used_rag else labels["footer"]
            draw = self._page_decoration(title, footer_text, language, stamp)
            SimpleDocTemplate(
                str(output_path), pagesize=A4,
                leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2.4 * cm, bottomMargin=2.2 * cm,
                title=title, author="REX AI",
            ).build(story, onFirstPage=draw, onLaterPages=draw)

            return AgentResult(
                self.name, True,
                output={"document_type": doc_type, "file_path": str(output_path.resolve()),
                        "language": language, "title": title},
                message=f"PDF created successfully: {output_path.resolve()}",
            )
        except Exception as error:
            logger.exception("DocumentAgent failed for type=%s", doc_type)
            return AgentResult(self.name, False, message=f"Could not generate PDF: {error}")

    # ------------------------------------------------- language and building
    @staticmethod
    def _strings(value):
        if isinstance(value, str):
            yield value
        elif isinstance(value, dict):
            for v in value.values():
                yield from DocumentAgent._strings(v)
        elif isinstance(value, (list, tuple)):
            for v in value:
                yield from DocumentAgent._strings(v)

    def _pick_language(self, requested, title, meta, content, simple_lines) -> str:
        requested = str(requested or "auto").lower()
        if requested in ("en", "ar"):
            return requested
        sample = " ".join(self._strings([title, content if simple_lines is None else simple_lines,
                                         list(meta.values())]))
        return "ar" if arabic.is_mostly_arabic(sample) else "en"

    @staticmethod
    def _default_title(doc_type, c) -> str:
        course = c.get("course", "Course")
        ar = c.get("language") == "ar"
        return {
            "curriculum_report": f"{course} - " + ("المنهج الدراسي" if ar else "Curriculum"),
            "course_description": course,
            "gap_analysis": f"{course} - " + ("تقرير فجوات الاعتماد" if ar else "Accreditation Gap Report"),
        }[doc_type]

    def _content_from_curriculum(self, doc_type, c, task):
        ar = c.get("language") == "ar"
        from rex.utils.catalog import LEVEL_AR
        level_label = LEVEL_AR.get(c.get("level", ""), c.get("level", "")) if ar else c.get("level", "")
        modules = [m for m in c["modules"] if isinstance(m, dict)]
        hours = c.get("duration_hours", 0)
        hours_text = f"{hours:g}" if isinstance(hours, (int, float)) else str(hours)
        if doc_type == "curriculum_report":
            overview = (f"{c.get('course', '')} - المستوى {level_label}، {hours_text} ساعة تدريبية."
                        if ar else f"{c.get('course', '')} - {c.get('level', '')} level, {hours_text} training hours.")
            history = []
            events_ar = {"generated": "إنشاء", "revised": "تعديل", "approved": "اعتماد",
                         "changes_requested": "طلب تعديلات"}
            for h in c.get("history", []):
                who = f" - {h['by']}" if h.get("by") else ""
                note = f": {h['note']}" if h.get("note") else ""
                event = events_ar.get(h.get("event"), h.get("event", "")) if ar else h.get("event", "")
                history.append(f"v{h.get('version', '')} {event}{who} ({h.get('at', '')}){note}".strip())
            return {
                "overview": overview, "objectives": c.get("objectives") or c.get("learning_outcomes") or [],
                "prerequisites": c.get("prerequisites", ""),
                "modules": [{"title": m.get("title", ""), "topics": m.get("topics") or [m.get("title", "")],
                             "hours": m.get("duration_hours", m.get("hours", ""))} for m in modules],
                "assessments": c.get("assessments", []), "capstone": c.get("capstone", ""),
                "history": history,
            }
        if doc_type == "course_description":
            info = task.get("course_info") or {}
            pick = (lambda k: info.get(f"{k}_ar") or info.get(k)) if ar else (lambda k: info.get(k))
            formats = info.get("formats") or []
            if ar:
                from rex.utils.catalog import FORMAT_AR
                formats = [FORMAT_AR.get(f, f) for f in formats]
            fee = info.get("price_egp")
            return {
                "pitch": pick("description") or c.get("course", ""),
                "audience": pick("target_audience") or "",
                "level": level_label,
                "duration": (f"{hours_text} ساعة" if ar else f"{hours_text} hours"),
                "format": ", ".join(formats),
                "fee": (f"{fee:,} جنيه" if ar else f"EGP {fee:,}") if isinstance(fee, (int, float)) else "",
                "prerequisites": c.get("prerequisites", ""),
                "outcomes": c.get("learning_outcomes", []),
                "careers": pick("career_opportunities") or [],
            }
        gap = task.get("gap")
        if not isinstance(gap, dict) or "missing_topics" not in gap:
            return None
        covered, missing = gap.get("covered_topics", []), gap.get("missing_topics", [])
        total = len(covered) + len(missing)
        if ar:
            summary = f"تمت تغطية {len(covered)} من أصل {total} موضوعاً مطلوباً ({gap.get('coverage_percentage', 0)}٪)."
            covered_status, missing_status = "مغطّى", "غير مغطّى"
            rec_missing, rec_ok = "إضافة وحدة أو موضوع يغطي هذا المتطلب", "لا حاجة لإجراء"
        else:
            summary = (f"{len(covered)} of {total} required topics are covered "
                       f"({gap.get('coverage_percentage', 0)}%). This is an alignment check, not an accreditation.")
            covered_status, missing_status = "Covered", "Missing"
            rec_missing, rec_ok = "Add a module or topic that covers this requirement", "No action needed"
        return {
            "summary": summary,
            "gaps": [{"requirement": t, "status": missing_status, "severity": "-", "recommendation": rec_missing}
                     for t in missing] +
                    [{"requirement": t, "status": covered_status, "severity": "-", "recommendation": rec_ok}
                     for t in covered],
            "recommended_actions": ([f"{rec_missing}: {t}" for t in missing[:5]]
                                    or ["لا توجد فجوات - راجع المنهج مع المدرّب" if ar
                                        else "No gaps found - review with the instructor"]),
        }

    # ------------------------------------------------------- knowledge base
    def _rag_context(self, course_name: str) -> str:
        """First 300 chars of each knowledge-base doc that mentions the course title."""
        needle = course_name.strip().casefold()
        docs_dir = Path(__file__).resolve().parents[2] / "data" / "rag_docs"
        if not needle or not docs_dir.exists():
            return ""
        try:
            snippets = []
            for md_file in sorted(docs_dir.glob("*.md")):
                text = md_file.read_text(encoding="utf-8", errors="ignore")
                if needle in text.casefold():
                    snippets.append(text[:300])
            return " ".join(snippets)
        except OSError:
            return ""

    def _auto_generate_content(self, doc_type: str, title: str, meta: dict, rag_context: str) -> dict:
        """Draft content used only when the caller supplied none (nothing is invented)."""
        course_name = meta.get("Course", title)
        audience = meta.get("Audience", "To be confirmed")
        level = meta.get("Level", "To be confirmed")
        base_overview = rag_context if rag_context else f"Draft training program for {course_name}."
        if doc_type == "curriculum_report":
            return {"overview": f"{base_overview[:300]} (Draft - to be completed by the course owner.)",
                    "objectives": [f"To be defined for {course_name}"], "modules": [],
                    "assessments": [], "capstone": ""}
        if doc_type == "course_description":
            return {"pitch": f"{course_name} - draft course description.", "audience": audience, "level": level,
                    "duration": "To be confirmed", "format": "To be confirmed", "fee": "To be confirmed",
                    "prerequisites": "To be confirmed", "outcomes": [], "careers": []}
        return {"summary": f"Draft gap analysis for {course_name}. No gaps have been entered yet.",
                "gaps": [], "recommended_actions": []}

    # ----------------------------------------------------------- text helpers
    def _font(self, bold=False) -> str:
        reg, bld = arabic.register_fonts()
        return bld if bold else reg

    def _styles(self):
        s = getSampleStyleSheet()
        rtl = self._rtl
        base_font = self._font() if rtl else "Helvetica"
        bold_font = self._font(True) if rtl else "Helvetica-Bold"
        align = TA_RIGHT if rtl else TA_LEFT
        s["Title"].fontName = bold_font
        s["Title"].textColor = NAVY
        s["Title"].alignment = TA_CENTER
        s.add(ParagraphStyle("SectionH2", parent=s["Heading2"], fontName=bold_font, textColor=NAVY,
                             spaceBefore=14, spaceAfter=6, alignment=align))
        s.add(ParagraphStyle("Meta", parent=s["Normal"], fontName=base_font, fontSize=9,
                             textColor=colors.grey, alignment=TA_CENTER if not rtl else TA_CENTER))
        s.add(ParagraphStyle("Body", parent=s["BodyText"], fontName=base_font, leading=15, alignment=align))
        s.add(ParagraphStyle("Cell", parent=s["Normal"], fontName=base_font, fontSize=9, leading=11, alignment=align))
        s.add(ParagraphStyle("CellHead", parent=s["Cell"], textColor=colors.white, fontName=bold_font))
        return s

    def _para(self, value, style, width=FRAME_W) -> Paragraph:
        """Paragraph that handles Arabic: shaped, wrapped on logical text, right aligned."""
        text = "" if value is None else str(value)
        if self._rtl or arabic.has_arabic(text):
            rtl_line = self._rtl or arabic.is_mostly_arabic(text)
            font = self._font(style.fontName.endswith("Bold"))
            lines = arabic.wrap_visual(text, font, style.fontSize, max(width, 20), rtl=rtl_line)
            local = ParagraphStyle(style.name + "-ar", parent=style, fontName=font,
                                   alignment=TA_RIGHT if rtl_line else style.alignment,
                                   wordWrap=None)
            return Paragraph("<br/>".join(escape(line) for line in lines), local)
        return Paragraph(escape(text), style)

    def _header(self, title, meta, styles):
        out = [self._para(title, styles["Title"]), Spacer(1, 6)]
        if meta:
            labels = LABELS[self._lang]["meta"]
            line = "  |  ".join(f"{labels.get(str(k), k)}: {v}" for k, v in meta.items() if str(v).strip())
            if line:
                out.append(self._para(line, styles["Meta"]))
        out += [Spacer(1, 6), HRFlowable(width="100%", thickness=1.2, color=NAVY), Spacer(1, 12)]
        return out

    def _footer(self, styles, used_rag=False):
        return [Spacer(1, 18), HRFlowable(width="100%", thickness=0.5, color=colors.lightgrey)]

    def _page_decoration(self, title, footer_text, language, stamp):
        """Brand bar, running title, page number and footer note on every page."""
        rtl = language == "ar"
        font = self._font() if rtl else "Helvetica"
        page_word = LABELS[language]["page"]
        draft = stamp is not None and stamp.get("status_code") != "approved"
        short_title = title if len(title) <= 70 else title[:67] + "..."

        def draw(canvas, doc):
            canvas.saveState()
            width, height = A4
            canvas.setFillColor(NAVY)
            canvas.rect(0, height - 1.1 * cm, width, 1.1 * cm, stroke=0, fill=1)
            canvas.setFillColor(colors.white)
            canvas.setFont(self._font(True) if rtl else "Helvetica-Bold", 10)
            canvas.drawString(2 * cm, height - 0.72 * cm, "REX AI")
            canvas.setFont(font, 9)
            running = arabic.visual(short_title, rtl) if rtl else short_title
            canvas.drawRightString(width - 2 * cm, height - 0.72 * cm, running)
            if draft:
                canvas.setFillColor(colors.HexColor("#B45309"))
                label = arabic.visual("مسودة - غير معتمدة", True) if rtl else "DRAFT - NOT APPROVED"
                canvas.setFont(font, 8)
                canvas.drawCentredString(width / 2, height - 1.6 * cm, label)
            canvas.setFillColor(colors.grey)
            canvas.setFont(font, 7.5)
            note = arabic.visual(footer_text, rtl) if rtl else footer_text
            canvas.drawCentredString(width / 2, 1.3 * cm, note if len(note) < 140 else note)
            number = f"{page_word} {doc.page}"
            canvas.drawCentredString(width / 2, 0.8 * cm, arabic.visual(number, rtl) if rtl else number)
            canvas.restoreState()

        return draw

    @staticmethod
    def _as_list(value):
        if value is None:
            return []
        if isinstance(value, (list, tuple)):
            return list(value)
        return [value]  # a lone string must not be split into characters

    def _bullets(self, items, styles, width=FRAME_W):
        cleaned = [str(i) for i in self._as_list(items) if str(i).strip()]
        if not cleaned:
            return Spacer(1, 1)
        if not self._rtl:
            return ListFlowable(
                [ListItem(self._para(t, styles["Body"], width - 16)) for t in cleaned],
                bulletType="bullet", start="•", leftIndent=14, bulletFontSize=10,
            )
        rows = [[self._para(t, styles["Body"], width - 18), self._para("•", styles["Body"], 14)] for t in cleaned]
        table = Table(rows, colWidths=[width - 18, 14])
        table.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                                   ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                                   ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]))
        return table

    def _cell(self, value, styles, head=False, width=FRAME_W):
        """Table cell as a Paragraph so text wraps and Arabic is shaped."""
        return self._para(value, styles["CellHead" if head else "Cell"], width - 12)

    def _data_table(self, rows, col_widths, styles, header_bg="#1F3A5F"):
        if self._rtl:  # first column on the right
            rows = [list(reversed(r)) for r in rows]
            col_widths = list(reversed(col_widths))
        data = [[self._cell(c, styles, head=(r == 0), width=col_widths[i]) for i, c in enumerate(row)]
                for r, row in enumerate(rows)]
        t = Table(data, colWidths=col_widths, repeatRows=1)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(header_bg)),
            ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7F9FC")]),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#B8C2D0")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        return t

    def _kv_table(self, pairs, styles):
        widths = [4 * cm, 12 * cm]
        rows = [[k, v] for k, v in pairs]
        if self._rtl:
            rows = [list(reversed(r)) for r in rows]
            widths = list(reversed(widths))
        data = [[self._cell(c, styles, width=widths[i]) for i, c in enumerate(row)] for row in rows]
        t = Table(data, colWidths=widths)
        shade = (1, 0) if self._rtl else (0, 0)
        t.setStyle(TableStyle([
            ("BACKGROUND", (shade[0], 0), (shade[0], -1), SOFT),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#B8C2D0")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        return t

    # ----------------------------------------------------------------- builders
    def _h(self, key, styles):
        return self._para(LABELS[self._lang][key], styles["SectionH2"])

    def _build_simple(self, lines, styles):
        out = []
        for line in lines:
            out += [self._para(line, styles["Body"]), Spacer(1, 6)]
        return out

    def _build_curriculum_report(self, c, styles):
        L = LABELS[self._lang]
        out = []
        if c.get("overview"):
            out += [self._h("overview", styles), self._para(c["overview"], styles["Body"])]
        if c.get("objectives"):
            out += [self._h("objectives", styles), self._bullets(c["objectives"], styles)]
        if c.get("prerequisites"):
            out += [self._h("prerequisites", styles), self._para(c["prerequisites"], styles["Body"])]
        modules = [m for m in self._as_list(c.get("modules")) if isinstance(m, dict)]
        if modules:
            rows = [L["cols_modules"]]
            for i, m in enumerate(modules, 1):
                topics = ", ".join(str(t) for t in self._as_list(m.get("topics")))
                hours = m.get("hours", m.get("duration_hours", ""))
                rows.append([str(i), m.get("title", ""), topics, f"{hours:g}" if isinstance(hours, float) else hours])
            out += [self._h("modules", styles),
                    self._data_table(rows, [1 * cm, 5 * cm, 8 * cm, 2 * cm], styles)]
        if c.get("assessments"):
            out += [self._h("assessments", styles), self._bullets(c["assessments"], styles)]
        if c.get("capstone"):
            out += [self._h("capstone", styles), self._para(c["capstone"], styles["Body"])]
        if c.get("history"):
            out += [self._h("history", styles), self._bullets(c["history"], styles)]
        return out

    def _build_course_description(self, c, styles):
        L = LABELS[self._lang]
        out = []
        if c.get("pitch"):
            out += [self._para(c["pitch"], styles["Body"]), Spacer(1, 6)]
        facts = [(L["facts"][k], c[k]) for k in ("audience", "level", "duration", "format", "fee", "prerequisites")
                 if c.get(k)]
        if facts:
            out += [self._h("key_facts", styles), self._kv_table(facts, styles)]
        if c.get("outcomes"):
            out += [self._h("learn", styles), self._bullets(c["outcomes"], styles)]
        if c.get("careers"):
            out += [self._h("careers", styles), self._bullets(c["careers"], styles)]
        return out

    def _build_gap_analysis(self, c, styles):
        L = LABELS[self._lang]
        out = []
        if c.get("summary"):
            out += [self._h("summary", styles), self._para(c["summary"], styles["Body"])]
        gaps = [g for g in self._as_list(c.get("gaps")) if isinstance(g, dict)]
        if gaps:
            rows = [L["cols_gaps"]]
            for g in gaps:
                rows.append([g.get("requirement", ""), g.get("status", ""), g.get("severity", ""),
                             g.get("recommendation", "")])
            out += [self._h("gap_details", styles),
                    self._data_table(rows, [4.5 * cm, 2.5 * cm, 2 * cm, 8 * cm], styles)]
        if c.get("recommended_actions"):
            out += [self._h("actions", styles), self._bullets(c["recommended_actions"], styles)]
        return out
