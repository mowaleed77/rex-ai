"""Document Generation Agent: professional PDFs in English or Arabic (right-to-left).

Task keys:
    document_type : curriculum_report | course_description | gap_analysis
    title         : str
    metadata      : dict  shown under the title (Course, Audience, Date ...)
    content       : dict | list[str] | None   typed content (see the _build_* methods), as before
    curriculum    : dict  OPTIONAL output of the Curriculum agent - the document is built from it directly
    gap           : dict  OPTIONAL output of the Curriculum agent's gap_analysis (for gap_analysis PDFs)
    course_info   : dict  OPTIONAL catalog entry (price, formats, careers ...) for course_description
    language      : "en" | "ar" | "auto" (default). "auto" picks Arabic when the text is mostly Arabic.
    output_dir    : folder for the PDF (default generated_docs/)

When `curriculum` is given, the PDF also shows its version and review status (draft / in review /
approved), so nobody mistakes a draft for an approved document.
"""
